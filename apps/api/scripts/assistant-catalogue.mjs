#!/usr/bin/env node
/**
 * Builds the workspace assistant's API catalogue: every route with the few lines that define it
 * (the request schema it parses), and the named zod schemas those lines use. The assistant
 * searches it ("find") before reading or proposing a call, so it knows the real field names.
 *
 *   node scripts/assistant-catalogue.mjs          writes src/services/assistant-catalogue.generated.ts
 *   node scripts/assistant-catalogue.mjs --check  exits 1 when the file is out of date
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src');
const OUT = join(root, 'services', 'assistant-catalogue.generated.ts');
const squash = (s, n) => {
  const t = s.replace(/\s+/g, ' ').trim();
  return t.length > n ? `${t.slice(0, n - 1)}…` : t;
};

export function build() {
  const files = (dir) => readdirSync(join(root, dir)).filter((f) => f.endsWith('.ts')).map((f) => join(root, dir, f));
  const all = [...files('routes'), ...files('services'), ...readdirSync(join(root, 'services'), { withFileTypes: true }).filter((d) => d.isDirectory()).flatMap((d) => files(join('services', d.name)))];
  // named schemas anywhere in routes / services
  const schemas = {};
  for (const f of all) {
    const lines = readFileSync(f, 'utf8').split('\n');
    lines.forEach((l, i) => {
      const m = /^(?:export )?const (\w+(?:Schema|Input))\s*=\s*(.*)$/.exec(l);
      if (!m) return;
      const body = [m[2]];
      let depth = (m[2].match(/[({[]/g) ?? []).length - (m[2].match(/[)}\]]/g) ?? []).length;
      for (let j = i + 1; j < lines.length && depth > 0 && j < i + 40; j++) {
        body.push(lines[j]);
        depth += (lines[j].match(/[({[]/g) ?? []).length - (lines[j].match(/[)}\]]/g) ?? []).length;
      }
      schemas[m[1]] ??= squash(body.join(' '), 1200);
    });
  }
  const routes = [];
  const used = new Set();
  for (const f of files('routes')) {
    const lines = readFileSync(f, 'utf8').split('\n');
    const defs = [];
    lines.forEach((l, i) => {
      const m = /^\s*\.(get|post|patch|put|delete)\(\s*'([^']+)'/.exec(l);
      if (m) defs.push({ i, m: m[1].toUpperCase(), p: m[2] });
    });
    defs.forEach((d, k) => {
      const end = Math.min(defs[k + 1]?.i ?? lines.length, d.i + 10);
      const s = squash(lines.slice(d.i, end).join(' '), 450);
      for (const n of s.matchAll(/\b(\w+(?:Schema|Input))\b/g)) if (schemas[n[1]]) used.add(n[1]);
      routes.push([d.m, d.p, s]);
    });
  }
  const kept = Object.fromEntries(Object.entries(schemas).filter(([k]) => used.has(k)).sort(([a], [b]) => a.localeCompare(b)));
  return `// Generated by scripts/assistant-catalogue.mjs: do not edit. Run \`pnpm --filter @synapse/api catalogue\` after changing routes.
/* eslint-disable */
export const ROUTE_SOURCES: [method: string, path: string, source: string][] = ${JSON.stringify(routes)};
export const SCHEMA_SOURCES: Record<string, string> = ${JSON.stringify(kept)};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = build();
  if (process.argv.includes('--check')) {
    let cur = '';
    try {
      cur = readFileSync(OUT, 'utf8');
    } catch {}
    if (cur !== text) {
      console.error('assistant-catalogue.generated.ts is out of date: run pnpm --filter @synapse/api catalogue');
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT} (${Math.round(text.length / 1024)} KB)`);
  }
}
