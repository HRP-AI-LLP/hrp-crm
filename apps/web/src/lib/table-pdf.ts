/**
 * Tables as PDF reports, to share with management: the company's name, the report title, any filters, who
 * made it and when (IST) on top; page numbers and the generation note at the foot of every page; amounts
 * right-aligned, with the ₹ sign (an embedded subset of DejaVu Sans). jsPDF and the font load only when a
 * report is exported.
 */
import { get } from './api';

export type PdfCell = string | { content: string; colSpan?: number };

export interface PdfReport {
  title: string;
  /** e.g. the filters, the period, "first 5,000 rows" */
  subtitle?: string | null;
  head: string[];
  body: PdfCell[][];
  foot?: PdfCell[][];
  fileName?: string;
}

/** Who and for whom: set once by the app shell (the signed-in person and workspace). */
const context: { user: string; workspace: string } = { user: '', workspace: '' };
export function setPdfContext(c: { user: string; workspace: string }) {
  Object.assign(context, c);
}

let orgName: Promise<{ name: string; gstin: string }> | null = null;
function organisation() {
  orgName ??= get<{ profile?: { legalName?: string; tradeName?: string; gstin?: string } }>('/api/v1/organisation')
    .then((d) => ({ name: d.profile?.legalName || d.profile?.tradeName || context.workspace, gstin: d.profile?.gstin ?? '' }))
    .catch(() => ({ name: context.workspace, gstin: '' }));
  return orgName;
}

const b64 = (buf: ArrayBuffer) => {
  const u = new Uint8Array(buf);
  let s = '';
  for (let i = 0; i < u.length; i += 0x8000) s += String.fromCharCode(...u.subarray(i, i + 0x8000));
  return btoa(s);
};
let fonts: Promise<[string, string]> | null = null;
const loadFonts = () =>
  (fonts ??= Promise.all(['/fonts/pdf-sans.ttf', '/fonts/pdf-sans-bold.ttf'].map((u) => fetch(u).then((r) => (r.ok ? r.arrayBuffer() : Promise.reject(new Error('Could not load the PDF font')))).then(b64))) as Promise<[string, string]>);

const NUMERIC = /^\s*\(?[-−+]?\s?[₹$€£]?\s?\d[\d,]*(\.\d+)?\s*%?\)?\s*(Dr|Cr|cr|dr|L|K|lakh|Cr\.?)?\s*$/;
const istNow = () => new Date().toLocaleString('en-IN', { dateStyle: 'medium', timeStyle: 'short', timeZone: 'Asia/Kolkata' });
const slug = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 60) || 'report';

const text = (c: PdfCell) => (typeof c === 'string' ? c : c.content);

export async function exportReportPdf(r: PdfReport) {
  const [{ jsPDF }, plugin, [regular, bold], org] = await Promise.all([import('jspdf'), import('jspdf-autotable'), loadFonts(), organisation()]);
  // the plugin's function is its default export, or wrapped once more by the bundler's CommonJS interop
  type AutoTable = typeof import('jspdf-autotable').default;
  const m = plugin as unknown as { default?: AutoTable | { default?: AutoTable }; autoTable?: AutoTable };
  const autoTable = (typeof m.default === 'function' ? m.default : (m.default as { default?: AutoTable } | undefined)?.default ?? m.autoTable) as AutoTable;
  if (typeof autoTable !== 'function') throw new Error('Could not load the PDF table maker');
  // wide tables go landscape: by column count, or by how much text the widest rows hold
  const widest = Math.max(r.head.join('  ').length, ...r.body.slice(0, 200).map((row) => row.map(text).join('  ').length));
  const landscape = r.head.length > 6 || widest > 120;
  const doc = new jsPDF({ orientation: landscape ? 'landscape' : 'portrait', unit: 'pt', format: 'a4' });
  doc.addFileToVFS('pdf-sans.ttf', regular);
  doc.addFont('pdf-sans.ttf', 'PdfSans', 'normal');
  doc.addFileToVFS('pdf-sans-bold.ttf', bold);
  doc.addFont('pdf-sans-bold.ttf', 'PdfSans', 'bold');
  doc.setFont('PdfSans', 'normal');
  doc.setProperties({ title: r.title, subject: r.subtitle ?? '', author: context.user, creator: 'HRP Synapse' });

  const W = doc.internal.pageSize.getWidth();
  const H = doc.internal.pageSize.getHeight();
  const M = 36;
  const generated = `Generated by ${context.user || 'Synapse'} on ${istNow()} IST`;
  const navy: [number, number, number] = [15, 43, 91];

  // the first page's heading
  let y = M;
  doc.setFont('PdfSans', 'bold').setFontSize(10).setTextColor(90);
  doc.text(org.name + (org.gstin ? `  ·  GSTIN ${org.gstin}` : ''), M, y);
  y += 20;
  doc.setFontSize(15).setTextColor(...navy);
  const titleLines = doc.splitTextToSize(r.title, W - 2 * M) as string[];
  doc.text(titleLines, M, y);
  y += titleLines.length * 18;
  doc.setFont('PdfSans', 'normal').setFontSize(8.5).setTextColor(100);
  if (r.subtitle) {
    const sub = doc.splitTextToSize(r.subtitle, W - 2 * M) as string[];
    doc.text(sub, M, y);
    y += sub.length * 11;
  }
  doc.text(`${r.body.length.toLocaleString('en-IN')} row${r.body.length === 1 ? '' : 's'}  ·  ${generated}`, M, y);
  y += 10;

  // which columns hold amounts (a column of only "—" counts as one when the table has amounts at all)
  const BLANK = /^\s*[—–-]?\s*$/;
  const numericCols = new Set<number>();
  const blankCols: number[] = [];
  r.head.forEach((_, i) => {
    const vals = r.body.slice(0, 200).map((row) => text(row[i] ?? '')).filter((v) => !BLANK.test(v));
    if (!vals.length) blankCols.push(i);
    else if (vals.filter((v) => NUMERIC.test(v)).length / vals.length > 0.8) numericCols.add(i);
  });
  if (numericCols.size) for (const i of blankCols) numericCols.add(i);

  const totalPages = '{total_pages}';
  autoTable(doc, {
    head: [r.head],
    body: r.body,
    foot: r.foot,
    startY: y + 6,
    margin: { top: M + 18, bottom: M, left: M, right: M },
    theme: 'grid',
    showHead: 'everyPage',
    showFoot: 'lastPage',
    styles: { font: 'PdfSans', fontSize: landscape ? 7.5 : 8, cellPadding: 3.5, lineColor: [221, 226, 234], lineWidth: 0.5, textColor: [30, 35, 45], overflow: 'linebreak', valign: 'top' },
    headStyles: { font: 'PdfSans', fontStyle: 'bold', fillColor: navy, textColor: 255, valign: 'middle' },
    footStyles: { font: 'PdfSans', fontStyle: 'bold', fillColor: [238, 242, 248], textColor: [20, 25, 35] },
    alternateRowStyles: { fillColor: [247, 249, 252] },
    didParseCell: (d) => {
      const raw = Array.isArray(d.cell.text) ? d.cell.text.join(' ') : String(d.cell.text ?? '');
      // amounts, and the headings and blanks ("—") of amount columns, line up on the right
      if (numericCols.has(d.column.index) && (d.section === 'head' || !raw || BLANK.test(raw) || NUMERIC.test(raw))) d.cell.styles.halign = 'right';
      else if (d.section !== 'head' && raw && NUMERIC.test(raw)) d.cell.styles.halign = 'right';
    },
    didDrawPage: (d) => {
      // later pages: a slim running heading
      if (d.pageNumber > 1) {
        doc.setFont('PdfSans', 'bold').setFontSize(8.5).setTextColor(...navy);
        doc.text(`${org.name}  ·  ${r.title}`.slice(0, 140), M, M);
      }
      doc.setDrawColor(221, 226, 234).setLineWidth(0.5).line(M, H - M + 8, W - M, H - M + 8);
      doc.setFont('PdfSans', 'normal').setFontSize(7.5).setTextColor(120);
      doc.text(generated, M, H - M + 20);
      doc.text(`Page ${d.pageNumber} of ${totalPages}`, W - M, H - M + 20, { align: 'right' });
    },
  });
  if (typeof (doc as unknown as { putTotalPages?: (s: string) => void }).putTotalPages === 'function') (doc as unknown as { putTotalPages: (s: string) => void }).putTotalPages(totalPages);
  const name = r.fileName ?? `${slug(r.title)}-${new Date().toISOString().slice(0, 10)}.pdf`;
  doc.save(name);
  return name;
}

/* ───────────────────────── reading a table on screen ───────────────────────── */

/** The text a person sees in a cell: form fields by their value, buttons and icons left out. */
function cellText(cell: Element): string {
  const c = cell.cloneNode(true) as HTMLElement;
  // form fields: their current values (clone loses them, so read from the original)
  const live = cell.querySelectorAll('input, select, textarea');
  c.querySelectorAll('input, select, textarea').forEach((el, i) => {
    const src = live[i] as HTMLInputElement | HTMLSelectElement | HTMLTextAreaElement;
    let v = '';
    if (src instanceof HTMLSelectElement) v = src.selectedOptions[0]?.text ?? '';
    else if (src instanceof HTMLInputElement && ['checkbox', 'radio', 'file', 'hidden'].includes(src.type)) v = ''; // selection boxes are not data
    else v = src.value;
    el.replaceWith(document.createTextNode(v));
  });
  c.querySelectorAll('button, svg, [aria-hidden="true"], .sr-only, [data-export="skip"], .tbl-export').forEach((el) => el.remove());
  // a second line (a note under a name) on its own line; words in separate elements kept apart
  c.querySelectorAll('div, p, br, li, small, .muted, .small').forEach((el) => {
    el.before(document.createTextNode('\n'));
    el.after(document.createTextNode('\n'));
  });
  c.querySelectorAll('span, a, b, strong, em, code, .chip').forEach((el) => el.after(document.createTextNode(' ')));
  return (c.textContent ?? '')
    .split('\n')
    .map((l) => l.replace(/\s+/g, ' ').trim())
    .filter(Boolean)
    .join('\n');
}

function rowsOf(section: HTMLTableSectionElement | null): PdfCell[][] {
  if (!section) return [];
  return Array.from(section.rows)
    .filter((tr) => !tr.hidden && getComputedStyle(tr).display !== 'none')
    .map((tr) => Array.from(tr.cells).map((td) => (td.colSpan > 1 ? { content: cellText(td), colSpan: td.colSpan } : cellText(td))));
}

/** A table on screen as head / body / foot, with empty columns (selection boxes, action buttons) left out. */
export function readTable(table: HTMLTableElement): Pick<PdfReport, 'head' | 'body' | 'foot'> {
  const headRows = table.tHead ? Array.from(table.tHead.rows) : [];
  const headRow = headRows[headRows.length - 1];
  let head = headRow ? Array.from(headRow.cells).map((th) => cellText(th)) : [];
  let body = rowsOf(table.tBodies[0] ?? null);
  for (const tb of Array.from(table.tBodies).slice(1)) body = body.concat(rowsOf(tb));
  let foot = rowsOf(table.tFoot);
  const width = Math.max(head.length, ...body.map((r) => r.length));
  if (!head.length) head = Array.from({ length: width }, () => '');
  const spans = [...body, ...foot].some((r) => r.some((c) => typeof c !== 'string'));
  if (!spans) {
    // drop columns with no heading and nothing in them
    const keep = head.map((h, i) => !!h || body.some((r) => text(r[i] ?? '')) || foot.some((r) => text(r[i] ?? '')));
    head = head.filter((_, i) => keep[i]);
    body = body.map((r) => r.filter((_, i) => keep[i]));
    foot = foot.map((r) => r.filter((_, i) => keep[i]));
  }
  // an "empty" placeholder row is not data
  body = body.filter((r) => !(r.length === 1 && typeof r[0] !== 'string' && (r[0]!.colSpan ?? 1) >= width));
  return { head, body, foot: foot.length ? foot : undefined };
}

/** A heading for a table: its own, its panel's, the open tab and the page's. */
export function titleFor(table: HTMLTableElement): string {
  const own = table.getAttribute('data-export-title') || table.caption?.textContent?.trim();
  if (own) return own;
  const parts: string[] = [];
  const page = document.querySelector('main h1, .page-head h1, h1');
  if (page?.textContent?.trim()) parts.push(page.textContent.trim());
  const tab = document.querySelector('[role="tab"][aria-selected="true"]');
  if (tab?.textContent?.trim() && !(table.closest('.modal') && !tab.closest('.modal'))) parts.push(tab.textContent.trim());
  const modal = table.closest('.modal');
  const panelHead = modal?.querySelector('.modal-head h2, .modal-head h3, h2') ?? table.closest('.panel')?.querySelector('.panel-head h2, .panel-head h3, h2, h3');
  const ph = panelHead?.textContent?.trim();
  if (ph && !/^(preview|results?|data|details|list)$/i.test(ph)) parts.push(ph);
  const uniq = parts.filter((p, i) => parts.indexOf(p) === i);
  return uniq.join(' — ') || 'Report';
}
